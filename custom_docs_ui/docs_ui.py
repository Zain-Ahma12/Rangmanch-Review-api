def _decorate(page: str, app: FastAPI, openapi_url: str, docs_path: str) -> str:
    """Wrap FastAPI's generated Swagger UI page with the custom chrome."""
    links = [f'<a class="rm-ghost" href="{escape(openapi_url)}">OpenAPI JSON</a>']
    if app.redoc_url:
        links.append(f'<a class="rm-ghost" href="{escape(app.redoc_url)}">ReDoc</a>')

    body_start = (
        _BODY_START.replace("__TITLE__", escape(app.title))
        .replace("__VERSION__", escape(str(app.version)))
        .replace("__DOCS__", escape(docs_path))
        .replace("__LINKS__", "".join(links))
    )
    # "</" is escaped so the JSON can never close the <script> tag early.
    script = _SCRIPT.replace("__OPENAPI__", json.dumps(openapi_url).replace("</", "<\\/"))
    head = _HEAD.replace("__CSS__", _CSS)

    # Our <style> goes last in <head> so it wins over swagger-ui.css.
    page = re.sub(r"</head>", lambda _m: head + "</head>", page, count=1, flags=re.I)
    # Header + sidebar go first in <body>; Swagger's #swagger-ui stays untouched.
    page = re.sub(r"(<body[^>]*>)", lambda m: m.group(1) + body_start, page, count=1, flags=re.I)
    # Our script goes last, after Swagger's own init script.
    page = re.sub(r"</body>", lambda _m: script + "</body>", page, count=1, flags=re.I)
    return page


def setup_custom_docs(app: FastAPI, docs_path: str = "/docs") -> None:
    """Serve the themed Swagger UI at ``docs_path``.

    Create the app with ``docs_url=None`` and call this once.
    """

    async def custom_docs(req: Request) -> HTMLResponse:
        root_path = req.scope.get("root_path", "").rstrip("/")
        openapi_url = app.openapi_url or "/openapi.json"
        if root_path and root_path not in openapi_url:
            openapi_url = root_path + openapi_url

        oauth2_redirect = None
        if app.swagger_ui_oauth2_redirect_url:
            oauth2_redirect = root_path + app.swagger_ui_oauth2_redirect_url

        base = get_swagger_ui_html(
            openapi_url=openapi_url,
            title=f"{app.title} - API docs",
            swagger_js_url=SWAGGER_JS,
            swagger_css_url=SWAGGER_CSS,
            swagger_favicon_url=_FAVICON,
            oauth2_redirect_url=oauth2_redirect,
            init_oauth=app.swagger_ui_init_oauth,
            swagger_ui_parameters={**_SWAGGER_PARAMS, **(app.swagger_ui_parameters or {})},
        )
        html = _decorate(base.body.decode("utf-8"), app, openapi_url, root_path + docs_path)
        return HTMLResponse(html)

    app.add_api_route(docs_path, custom_docs, methods=["GET"], include_in_schema=False)

    # Needed by the "Authorize" dialog if you ever add OAuth2 (FastAPI registers
    # this itself only when docs_url is set, and we set it to None).
    if app.swagger_ui_oauth2_redirect_url:

        async def swagger_ui_redirect(req: Request) -> HTMLResponse:
            return get_swagger_ui_oauth2_redirect_html()

        app.add_route(
            app.swagger_ui_oauth2_redirect_url,
            swagger_ui_redirect,
            include_in_schema=False,
        )